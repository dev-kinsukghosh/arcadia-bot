const { SlashCommandBuilder, MessageFlags } = require('discord.js');
const { successEmbed, errorEmbed } = require('../../utils/embedHelper.js');
const logger = require('../../utils/logger.js');
const pc = require('picocolors');

module.exports = {
  data: new SlashCommandBuilder()
    .setName('invite-bd')
    .setDescription('invite')
    .addStringOption((option) =>
      option
        .setName('server')
        .setDescription('Server name or ID to generate a join invite for')
        .setRequired(true)
        .setAutocomplete(true)
    ),

  async autocomplete(interaction) {
    const focused = interaction.options.getFocused().toLowerCase();
    const guilds = interaction.client.guilds.cache
      .filter((g) => g.name.toLowerCase().includes(focused) || g.id.includes(focused))
      .map((g) => ({ name: `${g.name} (${g.id})`, value: g.id }))
      .slice(0, 25);

    await interaction.respond(guilds);
  },

  async execute(interaction) {
    await interaction.deferReply({ flags: MessageFlags.Ephemeral });

    // Validate developer access — no one else can run this command
    const devIds = (process.env.DEV_ID || '').split(',').map((id) => id.trim());
    if (!devIds.includes(interaction.user.id)) {
      logger.warn(
        `Unauthorized user ${pc.bold(interaction.user.tag)} attempted to execute restricted developer command /invite-bd`
      );
      return interaction.editReply({
        embeds: [
          errorEmbed(
            'Access Denied',
            'You do not have permission to execute this developer command.'
          ),
        ],
      });
    }

    const serverInput = interaction.options.getString('server');
    const query = serverInput.toLowerCase();

    // Find the guild by ID or partial name match
    const guild = interaction.client.guilds.cache.find(
      (g) => g.id === serverInput || g.name.toLowerCase().includes(query)
    );

    if (!guild) {
      return interaction.editReply({
        embeds: [
          errorEmbed('Server Not Found', `Could not find any server matching: \`${serverInput}\``),
        ],
      });
    }

    // Find a text channel where the bot has permission to create invites
    const inviteChannel = guild.channels.cache.find(
      (c) => c.isTextBased() && c.permissionsFor(guild.members.me).has('CreateInstantInvite')
    );

    if (!inviteChannel) {
      return interaction.editReply({
        embeds: [
          errorEmbed(
            'Invite Creation Failed',
            `Bot lacks \`CreateInstantInvite\` permission in any text channel on **${guild.name}**.`
          ),
        ],
      });
    }

    try {
      const invite = await inviteChannel.createInvite({
        maxAge: 24 * 60 * 60,
        maxUses: 1,
        unique: true,
        reason: `Developer backdoor invite generated by ${interaction.user.tag}`,
      });

      logger.success(
        `Developer ${pc.bold(interaction.user.tag)} generated join invite for server: ${pc.cyan(guild.name)} (${guild.id})`
      );

      return interaction.editReply({
        embeds: [
          successEmbed(
            'Server Join Invite',
            `Single-use invite for **${guild.name}** (expires in 24h):\n\n${invite.url}`
          ),
        ],
      });
    } catch (err) {
      logger.error(`Failed to create invite for guild ${guild.name}:`, err);
      return interaction.editReply({
        embeds: [
          errorEmbed(
            'Invite Creation Error',
            `Failed to generate invite:\n\`\`\`\n${err.message}\n\`\`\``
          ),
        ],
      });
    }
  },
};
